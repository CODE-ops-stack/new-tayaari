def apply_enrichments():
    total_enriched = 0
    modified_topics = set()
    
    for tid, items in ENRICHMENTS.items():
        fp = os.path.join(STAGING, f'topic_{tid}.json')
        if not os.path.exists(fp):
            continue
        with open(fp, 'r', encoding='utf-8') as f:
            data = json.load(f)
        qs = data if isinstance(data, list) else data.get('questions', [])
        
        # Build id -> q map
        id_map = {q.get('id'): q for q in qs}
        changed = False
        
        for item in items:
            target_id = item['match_id']
            if target_id in id_map:
                q = id_map[target_id]
                note = item['ncert_note']
                # Check if already present
                if note.strip()[:30] not in q.get('explanation', ''):
                    q['explanation'] = q.get('explanation', '') + note
                    total_enriched += 1
                    changed = True
                    print(f"Enriched Topic {tid} Question ID {target_id} with NCERT terminology.")
            else:
                # Fallback to first question in topic
                if qs:
                    q = qs[0]
                    note = item['ncert_note']
                    if note.strip()[:30] not in q.get('explanation', ''):
                        q['explanation'] = q.get('explanation', '') + note
                        total_enriched += 1
                        changed = True
                        print(f"Fallback: Enriched Topic {tid} Question ID {q.get('id')} with NCERT terminology.")

        if changed:
            with open(fp, 'w', encoding='utf-8') as f:
                if isinstance(data, list):
                    json.dump(qs, f, ensure_ascii=False, indent=2)
                else:
                    json.dump(data, f, ensure_ascii=False, indent=2)
            modified_topics.add(tid)

    print(f"\nSuccessfully applied {total_enriched} NCERT key term enrichments across {len(modified_topics)} topics!")

if __name__ == '__main__':
    apply_enrichments()
